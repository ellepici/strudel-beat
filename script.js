const colonne = lettere.reduce((tot, l) => tot + l[0].length, 0)

const ritmo = timeCat(...lettere.map(l => [l[0].length, glifo(l)]))
  .slow(colonne / 24)                              // ogni passo dura sempre 1/24 di ciclo
