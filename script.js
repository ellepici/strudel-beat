// --- da qui in giù: collegamento tra la pagina e Strudel ---

const canvas = document.getElementById('roll');
const roll = canvas.getContext('2d');

// il riquadro occupa tutto lo schermo (nitido anche sugli schermi retina)
function adatta() {
  const dpr = window.devicePixelRatio || 1;
  canvas.width = Math.round(innerWidth * dpr);
  canvas.height = Math.round(innerHeight * dpr);
}
adatta();
addEventListener('resize', adatta);

// editor di Strudel (nascosto con il CSS): serve solo a far suonare il codice
const repl = document.createElement('strudel-editor');
repl.setAttribute('code', codice.trim());
document.getElementById('editor').append(repl);

// il codice chiama disegna(ritmo): così la pagina sa cosa disegnare
let motivo = null;
window.disegna = (p) => { motivo = p; };

// inizio = punto (in cicli) da cui riparte il pattern, usato nel codice
window.inizio = 0;
let playing = false;

// posizione attuale nel pattern (in cicli): avanza mentre suona, resta ferma in pausa
function posizione() {
  return playing ? inizio + repl.editor.repl.scheduler.now() : inizio;
}

// --- disegno: 16 righe in altezza, ogni passo (1/24 di ciclo) è un quadrato ---
const RIGHE = 16;
const NOTA_ALTA = 47;   // la nota della riga 0 (nel codice: .note(47 - r))
const lato = () => canvas.height / RIGHE;     // lato di un pixel della lettera
const pxPerCiclo = () => lato() * 24;         // 24 passi per ciclo

// ingresso = quanti cicli servono per attraversare lo schermo da destra a sinistra
// (si ricalcola al reset, così vale per la larghezza attuale della finestra)
function calcolaIngresso() {
  const passi = Math.ceil(canvas.width / lato());   // passi che entrano nello schermo (arrotondato a un passo intero)
  window.ingresso = passi / 24;
}
calcolaIngresso();

// ogni colonna parte dal bordo destro e arriva al bordo sinistro esattamente quando suona
function disegnaFrame() {
  const W = canvas.width, H = canvas.height;
  const l = lato(), ppc = pxPerCiclo();
  const gap = Math.max(1, Math.round(l * 0.03));   // sottile riga nera tra i quadrati

  roll.fillStyle = '#000';
  roll.fillRect(0, 0, W, H);

  if (motivo) {
    const ora = posizione() - ingresso;       // il punto del ritmo che sta toccando il bordo sinistro
    const spessore = Math.max(2, Math.round(l * 0.06));   // contorno del quadrato che sta suonando
    roll.fillStyle = '#fff';
    roll.strokeStyle = '#fff';
    roll.lineWidth = spessore;
    for (const h of motivo.queryArc(ora, ora + W / ppc)) {
      if (!h.whole) continue;
      const b = h.whole.begin.valueOf();
      const e = h.whole.end.valueOf();
      const riga = NOTA_ALTA - h.value.note;
      const x = (b - ora) * ppc;
      const w = (e - b) * ppc - gap;
      if (b <= ora && ora < e) {
        // sta suonando adesso (tocca il bordo sinistro): solo il contorno, come nel pianoroll di Strudel
        roll.strokeRect(x + spessore / 2, riga * l + spessore / 2, w - spessore, l - gap - spessore);
      } else {
        roll.fillRect(x, riga * l, w, l - gap);
      }
    }
  }
  requestAnimationFrame(disegnaFrame);
}
requestAnimationFrame(disegnaFrame);

// --- comandi ---
const btnPlay = document.getElementById('toggle');
const btnReset = document.getElementById('reset');

function aggiornaPulsante() {
  btnPlay.textContent = playing ? '❚❚ pausa' : '▶ play';
}

// play / pausa: la pausa ricorda il punto, il play riparte da lì
async function playPausa() {
  if (playing) {
    window.inizio = posizione();
    playing = false;
    await repl.editor.stop();
  } else {
    await repl.editor.evaluate();
    playing = true;
  }
  aggiornaPulsante();
}

// reset: torna all'inizio con lo schermo vuoto (se stava suonando, riparte subito)
async function reset() {
  if (playing) {
    playing = false;
    await repl.editor.stop();
    window.inizio = 0;
    calcolaIngresso();
    await repl.editor.evaluate();
    playing = true;
  } else {
    window.inizio = 0;
    calcolaIngresso();
  }
}

btnPlay.onclick = playPausa;
btnReset.onclick = reset;
canvas.onclick = playPausa;
document.addEventListener('keydown', (e) => {
  if (e.code === 'Space') { e.preventDefault(); playPausa(); }   // barra spaziatrice = play / pausa
  if (e.key === 'r' || e.key === 'R') reset();                    // tasto R = reset
});