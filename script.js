// toglie le colonne vuote ai lati della lettera e aggiunge lo spazio scelto
const ritaglia = righe => {
  const piene = [...Array(righe[0].length).keys()].filter(c => righe.some(r => r[c] === '#'))
  if (piene.length === 0) return righe.map(() => '.'.repeat(4))   // spazio tra le parole
  const da = piene[0], a = piene[piene.length - 1] + 1
  return righe.map(r => r.slice(da, a) + '.'.repeat(spazio))
}

// una lettera = 16 righe, ogni colonna è un passo
const glifo = righe => stack(...righe.map((riga, r) =>
  s(seq(...riga.split('').map(c => c === '#' ? suoni[r] : silence)))
    .note(47 - r)   // riga 11 (linea di base) = nota 36, la cassa suona all'altezza originale
))

// mette le lettere una dopo l'altra, ognuna lunga quanto le sue colonne
