// scrivi una lettera o una parola: ogni lettera dura un ciclo (spazio = pausa)
const testo = 'abcdefghijklmnopqrstuvwxyz'

// uno strumento per riga, dall'alto in basso
const suoni = [
  'cr','rd','rd','oh',                  // ascendenti
  'hh','hh','rim','ht','cp','mt','sd','bd', // x-height (la cassa sulla linea di base)
  'lt','lt','bd','bd',                  // discendenti
]

const vuota = Array(16).fill('.'.repeat(24))
const glifo = ch => stack(...(alfabeto[ch] ?? vuota).map((riga, r) =>
  s(seq(...riga.split('').map(c => c === '#' ? suoni[r] : silence)))
    .note(47 - r)   // riga 11 (linea di base) = nota 36, la cassa suona all'altezza originale
))

cat(...testo.split('').map(glifo))
.bank('RolandTR909')
._pianoroll({ cycles: 1, playhead: 0, fill: 1, minMidi: 32, maxMidi: 47, autorange: 0, fold: 0 })
