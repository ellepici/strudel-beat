// scrivi una lettera o una parola: ogni lettera dura un ciclo (spazio = pausa)
const testo = 'abcdefghijklmnopqrstuvwxyz'

// 12 strumenti dall'alto in basso, ognuno copre 2 righe della griglia
const suoni = ['cr','rd','hh','oh','ht','rim','cp','sd','bd','mt','lt','bd']

const vuota = Array(24).fill('.'.repeat(24))
const glifo = ch => stack(...(alfabeto[ch] ?? vuota).map((riga, r) =>
  s(seq(...riga.split('').map(c => c === '#' ? suoni[Math.floor(r / 2)] : silence)))
    .note(52 - r)   // riga 16 (linea di base) = nota 36, la cassa suona all'altezza originale
))

cat(...testo.split('').map(glifo))
.bank('RolandTR909')
._pianoroll({ cycles: 1, playhead: 0, fill: 1, minMidi: 29, maxMidi: 52, autorange: 0, fold: 0 })
